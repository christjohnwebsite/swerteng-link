-- Run this in Supabase Dashboard > SQL Editor.
-- Do not put the Supabase service_role/secret key in any browser file.
create table if not exists public.player_links (
  id bigint generated by default as identity primary key,
  name text not null check (char_length(name) between 1 and 120),
  category text not null check (char_length(category) between 1 and 60),
  url text not null check (url ~* '^https?://'),
  description text,
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

alter table public.player_links enable row level security;

-- Visitors can read active links only.
drop policy if exists "Public can read active links" on public.player_links;
create policy "Public can read active links"
on public.player_links for select to anon, authenticated
using (is_active = true);

-- Authenticated users can view all rows so the admin can manage inactive links.
-- Before launch, replace this with the designated-admin UUID policy shown in README.md.
drop policy if exists "Authenticated users can read all links" on public.player_links;
create policy "Authenticated users can read all links"
on public.player_links for select to authenticated
using (true);

-- Authenticated users can manage rows. Only create accounts for trusted admins.
-- For tighter security, replace this with an allowlist of admin user UUIDs.
drop policy if exists "Authenticated admins can insert links" on public.player_links;
create policy "Authenticated admins can insert links"
on public.player_links for insert to authenticated
with check (true);

drop policy if exists "Authenticated admins can update links" on public.player_links;
create policy "Authenticated admins can update links"
on public.player_links for update to authenticated
using (true) with check (true);

drop policy if exists "Authenticated admins can delete links" on public.player_links;
create policy "Authenticated admins can delete links"
on public.player_links for delete to authenticated
using (true);

create index if not exists player_links_active_created_idx
on public.player_links (is_active, created_at desc);
create index if not exists player_links_category_idx
on public.player_links (category);

-- SECURITY NOTE:
-- These policies allow any authenticated Supabase user to manage links.
-- Before launch, use the README's admin-only UUID policy instead, then disable public signups.

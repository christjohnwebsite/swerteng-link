-- SWERTENG LINK analytics setup. Run once in Supabase SQL Editor.
create table if not exists public.analytics_events (
 id bigint generated by default as identity primary key,
 event_type text not null check (event_type in ('visit','click')),
 player_link_id text null,
 created_at timestamptz not null default now()
);
alter table public.analytics_events enable row level security;
drop policy if exists "Public can record analytics events" on public.analytics_events;
create policy "Public can record analytics events" on public.analytics_events for insert to anon, authenticated with check (event_type in ('visit','click'));
drop policy if exists "Admin can read analytics events" on public.analytics_events;
create policy "Admin can read analytics events" on public.analytics_events for select to authenticated using (auth.uid() = '390023fa-68ca-4f1f-9c27-382c49b9e576'::uuid);
